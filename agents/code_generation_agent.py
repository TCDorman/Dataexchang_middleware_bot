import json
from datetime import datetime
from pathlib import Path


# ==================================================
# Customer Name Normalization
# ==================================================
def get_safe_customer_name(customer_name: str) -> str:
    return customer_name.strip().lower().replace(" ", "_")


# ==================================================
# Integration Folder Setup
# ==================================================
def get_integration_folder(customer_name: str) -> Path:
    safe_name = get_safe_customer_name(customer_name)
    return Path("generated_integrations") / safe_name


# ==================================================
# Write JSON File
# ==================================================
def write_json_file(path: Path, data: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)

    with open(path, "w", encoding="utf-8") as file:
        json.dump(data, file, indent=4)


# ==================================================
# Load Customer Profile
# ==================================================
def load_customer_profile(customer_name: str) -> dict:
    safe_name = get_safe_customer_name(customer_name)

    profile_path = (
        Path("configs/customers")
        / f"{safe_name}_profile.json"
    )

    with open(
        profile_path,
        "r",
        encoding="utf-8",
    ) as file:
        return json.load(file)


# ==================================================
# Generate Config
# ==================================================
def generate_config(customer_name: str, source_type: str) -> dict:
    return {
        "customer_name": customer_name,
        "source_type": source_type,
        "target_system": "Modula WMS",
        "target_format": "wms_xml",
        "created_at": datetime.now().isoformat(),
        "input_folder": "data/customer_input",
        "output_folder": "data/output",
    }


# ==================================================
# Generate Runner Code
# ==================================================
def generate_runner_code(customer_name: str) -> str:
    return f'''"""
Generated middleware runner for {customer_name}.

This file was generated by the Modula WMS Data Integration Agent.
"""

import sys
from pathlib import Path

# Allow this generated script to import project modules
sys.path.append(str(Path(__file__).resolve().parents[2]))

from agents.master_agent import run_customer_import


def main():
    file_paths = [
        "data/customer_input/sample_file.csv",
    ]

    result = run_customer_import(
        "{customer_name}",
        file_paths,
    )

    print(result)


if __name__ == "__main__":
    main()
'''


# ==================================================
# Generate README
# ==================================================
def generate_readme(customer_name: str, source_type: str) -> str:
    safe_name = get_safe_customer_name(customer_name)

    return f"""# {customer_name} Modula WMS Integration

This folder contains generated middleware starter code for {customer_name}.

## Source Type

```text
{source_type}
```

## Target

Modula WMS XML

## Generated Files

- config.json
- mapping.json
- runner.py
- README.md

## How To Run

From the project root:

```bash
python generated_integrations/{safe_name}/runner.py
```

## Notes

This package was generated by the Modula WMS Data Integration Agent.

The generated runner is a starting point. File paths may need to be adjusted
for the customer's actual production folder structure.
"""


# ==================================================
# Generate Integration Package
# ==================================================
def generate_integration_package(
    customer_name: str,
    source_type: str,
    mapping: dict,
) -> dict:
    integration_folder = get_integration_folder(customer_name)

    integration_folder.mkdir(
        parents=True,
        exist_ok=True,
    )

    config = generate_config(
        customer_name,
        source_type,
    )

    write_json_file(
        integration_folder / "config.json",
        config,
    )

    write_json_file(
        integration_folder / "mapping.json",
        mapping,
    )

    with open(
        integration_folder / "runner.py",
        "w",
        encoding="utf-8",
    ) as file:
        file.write(
            generate_runner_code(customer_name)
        )

    with open(
        integration_folder / "README.md",
        "w",
        encoding="utf-8",
    ) as file:
        file.write(
            generate_readme(
                customer_name,
                source_type,
            )
        )

    return {
        "status": "success",
        "customer_name": customer_name,
        "integration_folder": str(integration_folder),
        "files_created": [
            str(integration_folder / "config.json"),
            str(integration_folder / "mapping.json"),
            str(integration_folder / "runner.py"),
            str(integration_folder / "README.md"),
        ],
    }


