# ==================================================
# Generate Integration Package
# ==================================================
def generate_integration_package(
    customer_name: str,
    source_type: str,
    mapping: dict,
) -> dict:
    """
    Generate a reusable middleware package for a customer.

    Output example:
    generated_integrations/ford/
        config.json
        mapping.json
        parser.py
        transformer.py
        runner.py
        README.md
    """
    integration_folder = get_integration_folder(customer_name)

    integration_folder.mkdir(
        parents=True,
        exist_ok=True,
    )

    config = generate_config(
        customer_name,
        source_type,
    )

    write_json_file(
        integration_folder / "config.json",
        config,
    )

    write_json_file(
        integration_folder / "mapping.json",
        mapping,
    )

    write_text_file(
        integration_folder / "parser.py",
        generate_parser_code(customer_name),
    )

    write_text_file(
        integration_folder / "transformer.py",
        generate_transformer_code(customer_name),
    )

    write_text_file(
        integration_folder / "runner.py",
        generate_runner_code(customer_name),
    )

    write_text_file(
        integration_folder / "README.md",
        generate_readme(
            customer_name,
            source_type,
        ),
    )

    return {
        "status": "success",
        "customer_name": customer_name,
        "integration_folder": str(integration_folder),
        "files_created": [
            str(integration_folder / "config.json"),
            str(integration_folder / "mapping.json"),
            str(integration_folder / "parser.py"),
            str(integration_folder / "transformer.py"),
            str(integration_folder / "runner.py"),
            str(integration_folder / "README.md"),
        ],
    }


