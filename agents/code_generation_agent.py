import json
from datetime import datetime
from pathlib import Path


# ==================================================
# Customer Name Normalization
# ==================================================
def get_safe_customer_name(customer_name: str) -> str:
    """
    Convert customer names into safe folder/file names.

    Example:
    Ford Motor Company -> ford_motor_company
    """
    return customer_name.strip().lower().replace(" ", "_")


# ==================================================
# Integration Folder Setup
# ==================================================
def get_integration_folder(customer_name: str) -> Path:
    """
    Return the generated integration folder path.
    """
    safe_name = get_safe_customer_name(customer_name)

    return Path("generated_integrations") / safe_name


# ==================================================
# Write JSON File
# ==================================================
def write_json_file(path: Path, data: dict) -> None:
    """
    Write a dictionary to a formatted JSON file.
    """
    path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    with open(path, "w", encoding="utf-8") as file:
        json.dump(data, file, indent=4)


# ==================================================
# Write Text File
# ==================================================
def write_text_file(path: Path, content: str) -> None:
    """
    Write generated code or documentation to a text file.
    """
    path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    with open(path, "w", encoding="utf-8") as file:
        file.write(content)


