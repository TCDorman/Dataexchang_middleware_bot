import os
import requests


# ==================================================
# Build Headers
# ==================================================
def build_headers(config: dict) -> dict:
    """
    Build request headers based on authentication settings.
    """
    headers = {{
        "Accept": "application/json",
    }}

    auth_type = config.get("auth_type", "none")

    if auth_type == "api_key":
        header_name = config.get("api_key_header")
        env_var = config.get("api_key_env_var")

        if not header_name:
            raise ValueError("Missing api_key_header in config.json")

        if not env_var:
            raise ValueError("Missing api_key_env_var in config.json")

        api_key = os.getenv(env_var)

        if not api_key:
            raise ValueError(
                f"Environment variable {{env_var}} is not set"
            )

        headers[header_name] = api_key

    return headers


# ==================================================
# Get Orders
# ==================================================
def get_orders(config: dict) -> list:
    """
    Fetch orders from the customer's REST API.
    """
    base_url = config["base_url"].rstrip("/")
    endpoint = config["orders_endpoint"].lstrip("/")

    url = f"{{base_url}}/{{endpoint}}"

    response = requests.get(
        url,
        headers=build_headers(config),
        timeout=30,
    )

    response.raise_for_status()

    data = response.json()

    if isinstance(data, list):
        return data

    if isinstance(data, dict):
        for key in ["orders", "data", "results", "items"]:
            if key in data and isinstance(data[key], list):
                return data[key]

    raise ValueError(
        "Could not locate order list in API response"
    )
