# ==================================================
# Generate REST Integration Package
# ==================================================
def generate_rest_integration_package(api_config: dict) -> dict:
    """
    Generate a reusable REST API integration package.

    Required api_config fields:
    - customer_name
    - base_url
    - orders_endpoint
    """
    required_fields = [
        "customer_name",
        "base_url",
        "orders_endpoint",
    ]

    for field in required_fields:
        if not api_config.get(field):
            raise ValueError(
                f"Missing required API config field: {field}"
            )

    customer_name = api_config["customer_name"]

    integration_folder = get_rest_integration_folder(
        customer_name
    )

    integration_folder.mkdir(
        parents=True,
        exist_ok=True,
    )

    config = generate_rest_config(api_config)

    write_json_file(
        integration_folder / "config.json",
        config,
    )

    write_text_file(
        integration_folder / "api_client.py",
        generate_api_client_code(customer_name),
    )

    write_text_file(
        integration_folder / "runner.py",
        generate_rest_runner_code(customer_name),
    )

    write_text_file(
        integration_folder / "README.md",
        generate_rest_readme(customer_name),
    )

    return {
        "status": "success",
        "customer_name": customer_name,
        "integration_folder": str(integration_folder),
        "files_created": [
            str(integration_folder / "config.json"),
            str(integration_folder / "api_client.py"),
            str(integration_folder / "runner.py"),
            str(integration_folder / "README.md"),
        ],
    }


