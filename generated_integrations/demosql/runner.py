"""
Generated SQL middleware runner for DemoSQL.

This file was generated by the Modula WMS Data Integration Agent.
"""

import json
import sys
from pathlib import Path

sys.path.append(str(Path(__file__).resolve().parents[2]))

from sql_client import fetch_rows
from parsers.rest_api_parser import parse_api_orders
from scripts.format_wms_xml import format_wms_xml
from transformers.wms_xml_transformer import export_orders_to_xml


# ==================================================
# Load Config
# ==================================================
def load_config() -> dict:
    """
    Load this package's config.json file.
    """
    config_path = Path(__file__).with_name("config.json")

    with open(config_path, "r", encoding="utf-8") as file:
        return json.load(file)


# ==================================================
# Main Runner
# ==================================================
def main():
    """
    Fetch rows from SQL and generate Modula WMS XML.
    """
    config = load_config()

    rows = fetch_rows(config)

    orders = parse_api_orders(rows)

    output_path = "data/output/demosql_sql_orders.xml"

    export_orders_to_xml(
        orders,
        output_path,
    )

    format_wms_xml(output_path)

    print(
        {
            "status": "success",
            "orders_converted": len(orders),
            "output_path": output_path,
        }
    )


if __name__ == "__main__":
    main()
