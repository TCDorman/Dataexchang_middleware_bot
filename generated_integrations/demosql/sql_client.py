import os

import pyodbc


# ==================================================
# Build Connection String
# ==================================================
def build_connection_string(config: dict) -> str:
    """
    Build an ODBC connection string from config.json.

    Supported first version:
    - SQL Server via ODBC Driver 17 for SQL Server
    """
    database_type = config.get("database_type")

    username_env_var = config.get("username_env_var")
    password_env_var = config.get("password_env_var")

    username = os.getenv(username_env_var) if username_env_var else None
    password = os.getenv(password_env_var) if password_env_var else None

    if database_type == "sql_server":
        if username and password:
            return (
                "DRIVER={ODBC Driver 17 for SQL Server};"
                f"SERVER={config['server']};"
                f"DATABASE={config['database']};"
                f"UID={username};"
                f"PWD={password};"
            )

        return (
            "DRIVER={ODBC Driver 17 for SQL Server};"
            f"SERVER={config['server']};"
            f"DATABASE={config['database']};"
            "Trusted_Connection=yes;"
        )

    if database_type == "odbc_dsn":
        dsn = config.get("dsn")

        if not dsn:
            raise ValueError("Missing dsn for odbc_dsn database type")

        if username and password:
            return (
                f"DSN={dsn};"
                f"UID={username};"
                f"PWD={password};"
            )

        return f"DSN={dsn};"

    raise ValueError(
        f"Unsupported database_type: {database_type}"
    )


