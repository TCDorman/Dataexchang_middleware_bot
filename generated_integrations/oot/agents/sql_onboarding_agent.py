# ==================================================
# Generate SQL Integration Package
# ==================================================
def generate_sql_integration_package(sql_config: dict) -> dict:
    """
    Generate a reusable SQL / ODBC integration package.

    Required sql_config fields:
    - customer_name
    - database_type
    - server
    - database
    - table
    """
    required_fields = [
        "customer_name",
        "database_type",
        "table",
    ]

    database_type = sql_config.get("database_type")

    if database_type == "sql_server":
        required_fields.extend(
            [
                "server",
                "database",
            ]
        )

    if database_type == "odbc_dsn":
        required_fields.append("dsn")

    for field in required_fields:
        if not sql_config.get(field):
            raise ValueError(
                f"Missing required SQL config field: {field}"
            )

    customer_name = sql_config["customer_name"]

    integration_folder = get_sql_integration_folder(
        customer_name
    )

    integration_folder.mkdir(
        parents=True,
        exist_ok=True,
    )

    config = generate_sql_config(sql_config)

    if database_type == "odbc_dsn":
        config["dsn"] = sql_config["dsn"]

    write_json_file(
        integration_folder / "config.json",
        config,
    )

    write_text_file(
        integration_folder / "sql_client.py",
        generate_sql_client_code(customer_name),
    )

    write_text_file(
        integration_folder / "runner.py",
        generate_sql_runner_code(customer_name),
    )

    write_text_file(
        integration_folder / "README.md",
        generate_sql_readme(customer_name),
    )

    return {
        "status": "success",
        "customer_name": customer_name,
        "integration_folder": str(integration_folder),
        "files_created": [
            str(integration_folder / "config.json"),
            str(integration_folder / "sql_client.py"),
            str(integration_folder / "runner.py"),
            str(integration_folder / "README.md"),
        ],
    }


