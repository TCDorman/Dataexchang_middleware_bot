import json
from datetime import datetime
from pathlib import Path


# ==================================================
# Safe Name Helper
# ==================================================
def get_safe_name(name: str) -> str:
    """
    Convert customer names into safe folder names.
    """
    return name.strip().lower().replace(" ", "_")


# ==================================================
# SQL Integration Folder
# ==================================================
def get_sql_integration_folder(customer_name: str) -> Path:
    """
    Return the generated SQL integration folder path.
    """
    safe_name = get_safe_name(customer_name)

    return Path("generated_integrations") / safe_name


# ==================================================
# Write JSON File
# ==================================================
def write_json_file(path: Path, data: dict) -> None:
    """
    Write formatted JSON to disk.
    """
    path.parent.mkdir(parents=True, exist_ok=True)

    with open(path, "w", encoding="utf-8") as file:
        json.dump(data, file, indent=4)


# ==================================================
# Write Text File
# ==================================================
def write_text_file(path: Path, content: str) -> None:
    """
    Write generated code or documentation to disk.
    """
    path.parent.mkdir(parents=True, exist_ok=True)

    with open(path, "w", encoding="utf-8") as file:
        file.write(content)


# ==================================================
# Generate SQL Config
# ==================================================
def generate_sql_config(sql_config: dict) -> dict:
    """
    Normalize SQL connection settings.
    """
    return {
        "customer_name": sql_config["customer_name"],
        "source_type": "sql",
        "target_system": "Modula WMS",
        "target_format": "wms_xml",
        "database_type": sql_config["database_type"],
        "server": sql_config["server"],
        "database": sql_config["database"],
        "table": sql_config["table"],
        "username_env_var": sql_config.get("username_env_var"),
        "password_env_var": sql_config.get("password_env_var"),
        "created_at": datetime.now().isoformat(),
        "output_folder": "data/output",
    }


